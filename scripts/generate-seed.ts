// Generates db/seed.sql from the structured catalog so TS data and SQL never drift.
//
// The BASE catalogue (4 phases, M1-M18, the two product paths, AI Mastery) lives in seed.sql. The profession modules
// (phase 5: marketing, HR, legal, finance) and their paths are created by migration 0012 so that databases that already
// exist get them too. `npm run seed:generate -- --migration` (re)writes that migration; it refuses to overwrite it
// unless --force is given, because a migration that was applied must never change.
import { existsSync, writeFileSync } from "node:fs";
import { courses, learningPaths, offers, phases, PROFESSION_PHASE } from "../src/lib/catalog/data";
import type { Course, LearningPath } from "../src/lib/catalog/types";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const offer = (slug: string) => offers.find((o) => o.slug === slug)!;

const isProfessionCourse = (c: Course) => c.phaseId === PROFESSION_PHASE;
const professionCodes = new Set(courses.filter(isProfessionCourse).map((c) => c.code));
const isProfessionPath = (p: LearningPath) => p.kind === "path" && p.courseCodes.some((c) => professionCodes.has(c));

/** Idempotent statements for one course: row, prerequisites, module product with its (closed) price. */
function courseSql(c: Course, idempotent: boolean): string[] {
  const out: string[] = [];
  const guard = idempotent ? " on conflict (code) do nothing" : "";
  out.push(
    `insert into courses (code, slug, title, summary, phase_id, position, status, difficulty, duration_hours, topics, tools, outcomes, deliverable, is_mvp_slot) values (${[
      q(c.code), q(c.slug), q(c.title), q(c.summary), c.phaseId, c.order, q(c.status), q(c.difficulty), c.durationHours,
      arr(c.topics), arr(c.tools), arr(c.outcomes), q(c.deliverable), c.mvpSlot,
    ].join(", ")})${guard};`,
  );
  for (const pre of c.prerequisites)
    out.push(`insert into course_prerequisites select c.id, p.id from courses c, courses p where c.code = ${q(c.code)} and p.code = ${q(pre)}${idempotent ? " on conflict do nothing" : ""};`);
  return out;
}

function moduleProductSql(c: Course, idempotent: boolean): string[] {
  const o = offer("module");
  const slug = q("module-" + c.slug);
  const where = idempotent ? ` and not exists (select 1 from products where slug = ${slug})` : "";
  return [
    `with p as (insert into products (slug, kind, title, course_id, access_months, active) select ${slug}, 'course', ${q(c.code + " — " + c.title)}, id, ${o.accessMonths}, false from courses where code = ${q(c.code)}${where} returning id)
insert into prices (product_id, amount_cents, tax_inclusive) select id, ${o.amountCents}, true from p;`,
    `insert into product_course_access select p.id, c.id from products p, courses c where p.slug = ${slug} and c.code = ${q(c.code)}${idempotent ? " on conflict do nothing" : ""};`,
  ];
}

function pathSql(p: LearningPath, idempotent: boolean): string[] {
  const out: string[] = [];
  const o = offer(p.slug);
  out.push(`insert into learning_paths (slug, title, tagline, audience, is_bundle, access_months) values (${q(p.slug)}, ${q(p.title)}, ${q(p.tagline)}, ${q(p.audience)}, ${p.kind === "bundle"}, ${p.accessMonths})${idempotent ? " on conflict (slug) do nothing" : ""};`);
  p.courseCodes.forEach((code, i) =>
    out.push(`insert into learning_path_courses select lp.id, c.id, ${i + 1} from learning_paths lp, courses c where lp.slug = ${q(p.slug)} and c.code = ${q(code)}${idempotent ? " on conflict do nothing" : ""};`));
  const where = idempotent ? ` and not exists (select 1 from products where slug = ${q(p.slug)})` : "";
  out.push(`with p as (insert into products (slug, kind, title, path_id, access_months, note, active) select ${q(p.slug)}, ${q(p.kind)}::product_kind, ${q(p.title)}, id, ${p.accessMonths}, ${o.note ? q(o.note) : "null"}, false from learning_paths where slug = ${q(p.slug)}${where} returning id)
insert into prices (product_id, amount_cents, tax_inclusive) select id, ${o.amountCents}, true from p;`);
  for (const code of p.courseCodes)
    out.push(`insert into product_course_access select pr.id, c.id from products pr, courses c where pr.slug = ${q(p.slug)} and c.code = ${q(code)}${idempotent ? " on conflict do nothing" : ""};`);
  return out;
}

// ───────── seed.sql: the base catalogue (a fresh database also gets the profession rows from migration 0012) ─────────
const baseCourses = courses.filter((c) => !isProfessionCourse(c));
const basePaths = learningPaths.filter((p) => !isProfessionPath(p));
const out: string[] = ["-- GENERATED by scripts/generate-seed.ts — do not edit by hand.", "-- No customers, revenue or testimonials are seeded.", ""];
for (const p of phases.filter((x) => x.id !== PROFESSION_PHASE)) out.push(`insert into learning_phases (id, slug, title, summary) values (${p.id}, ${q(p.slug)}, ${q(p.title)}, ${q(p.summary)});`);
out.push("");
for (const c of baseCourses) out.push(courseSql(c, false)[0]);
out.push("");
for (const c of baseCourses) out.push(...courseSql(c, false).slice(1));
out.push("");
for (const p of basePaths) {
  // AI Mastery covers every module; on a fresh database the profession courses already exist (migration 0012 runs first).
  out.push(...pathSql(p, false));
}
out.push("");
// Products: one per module + the paths/bundle. Prices are editable in admin; Stripe stays the payment source of truth.
// Everything starts closed (active = false): an offer opens only once its modules are published and priced.
// Enterprise needs are quotations (contact form), so no enterprise product is seeded.
for (const c of baseCourses) out.push(...moduleProductSql(c, false));
out.push("", "insert into system_settings (key, value) values ('legal_review_completed', 'false'::jsonb), ('live_checkout_enabled', 'false'::jsonb);");
writeFileSync("db/seed.sql", out.join("\n") + "\n");
console.log("seed.sql written");

// ───────── migration 0012: profession modules, for new and existing databases ─────────
if (process.argv.includes("--migration")) {
  const file = "db/migrations/0012_business_profiles.sql";
  if (existsSync(file) && !process.argv.includes("--force")) throw new Error(`${file} exists: an applied migration must not change (use --force only before it is applied anywhere)`);
  const profession = courses.filter(isProfessionCourse);
  const professionPaths = learningPaths.filter(isProfessionPath);
  const bundle = learningPaths.find((p) => p.kind === "bundle")!;
  const m: string[] = [
    "-- GENERATED by scripts/generate-seed.ts --migration. Idempotent: safe on a database that already holds the base catalogue.",
    "-- Adds phase 5 (IA pour les métiers), modules M19-M30, four profession paths, all closed for sale (active = false), and extends AI Mastery.",
    "",
  ];
  const ph = phases.find((x) => x.id === PROFESSION_PHASE)!;
  m.push(`insert into learning_phases (id, slug, title, summary) values (${ph.id}, ${q(ph.slug)}, ${q(ph.title)}, ${q(ph.summary)}) on conflict (id) do nothing;`, "");
  for (const c of profession) m.push(courseSql(c, true)[0]);
  for (const c of profession) m.push(...courseSql(c, true).slice(1));
  m.push("");
  for (const c of profession) m.push(...moduleProductSql(c, true));
  m.push("");
  for (const p of professionPaths) m.push(...pathSql(p, true));
  m.push("", "-- AI Mastery now covers every module.");
  m.push(`update learning_paths set tagline = ${q(bundle.tagline)}, audience = ${q(bundle.audience)} where slug = ${q(bundle.slug)};`);
  m.push(`update products set note = ${q(offer(bundle.slug).note ?? "")} where slug = ${q(bundle.slug)};`);
  bundle.courseCodes.forEach((code, i) => {
    if (!professionCodes.has(code)) return;
    m.push(`insert into learning_path_courses select lp.id, c.id, ${i + 1} from learning_paths lp, courses c where lp.slug = ${q(bundle.slug)} and c.code = ${q(code)} on conflict do nothing;`);
    m.push(`insert into product_course_access select pr.id, c.id from products pr, courses c where pr.slug = ${q(bundle.slug)} and c.code = ${q(code)} on conflict do nothing;`);
  });
  writeFileSync(file, m.join("\n") + "\n");
  console.log(`${file} written`);
}
